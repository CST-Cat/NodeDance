const assert=require('node:assert/strict'),path=require('node:path')
const {openNavigation,selectNodeSection}=require('./sidebar-navigation.cjs')
module.exports=async function({page,base,node,artifacts,headers,catalog}){
 const enrollment=catalog.operations.find(item=>item.name==='agents.enrollment');assert.ok(enrollment)
 const created=await page.request.post(base+enrollment.path,{headers,data:{displayName:'Navigation fixture',coreUrl:base}});assert.equal(created.status(),201);node=(await created.json()).nodeId
 const errors=[];page.on('pageerror',error=>errors.push(error.message))
 await page.setViewportSize({width:1440,height:1000})
 await page.goto(base+'/#/nodes')
 const sidebar=page.locator('#workspace-navigation'),toggle=page.locator('.navigation-toggle')
 const resize=sidebar.getByRole('separator')
 await resize.waitFor();await resize.focus();await page.keyboard.press('ArrowRight')
 const width=await resize.getAttribute('aria-valuenow')
 await page.locator(`.vps-card[data-node-id="${node}"] .vps-name`).click()
 const detail=page.getByTestId('node-detail-navigation');await detail.waitFor()
 assert.equal(await detail.locator('button').first().innerText(),'Back to home')
 assert.deepEqual((await detail.locator('button').allTextContents()).slice(1,4),['Overview','Docker details','Compose projects'])
 assert.equal(await page.locator('.dashboard-tabs').count(),0)
 assert.equal(await sidebar.getByRole('button',{name:'Alerts',exact:true}).count(),0,'Global navigation is replaced')
 assert.equal(await sidebar.getByRole('separator').getAttribute('aria-valuenow'),width,'Sidebar width survives entry')
 await toggle.click();assert.ok(await sidebar.evaluate(el=>el.classList.contains('is-collapsed')))
 assert.equal(await detail.getByRole('button',{name:'Node settings',exact:true}).getAttribute('title'),'Node settings')
 await toggle.click();assert.equal(await sidebar.getByRole('separator').getAttribute('aria-valuenow'),width)
 await selectNodeSection(page,'Node settings');await page.getByTestId('node-settings').waitFor()
 await page.reload();await detail.getByRole('button',{name:'Node settings',exact:true}).waitFor()
 assert.equal(await detail.getByRole('button',{name:'Node settings',exact:true}).getAttribute('aria-current'),'page')
 await detail.getByRole('button',{name:'Back to home',exact:true}).click();await page.locator('.nodes-dashboard').waitFor()
 await sidebar.getByRole('button',{name:'Alerts',exact:true}).waitFor()
 assert.equal(await sidebar.getByRole('separator').getAttribute('aria-valuenow'),width)
 await page.goBack();await page.getByTestId('node-settings').waitFor();await detail.waitFor()
 await page.goForward();await sidebar.getByRole('button',{name:'Alerts',exact:true}).waitFor()
 await page.goto(base+`/#/nodes?node=${node}&section=settings`);await detail.waitFor()
 for(const theme of ['light','dark'])for(const viewport of [390,1440]){
  await page.setViewportSize({width:viewport,height:1000})
  await page.locator('.app-shell').evaluate((el,theme)=>{el.dataset.theme=theme;document.documentElement.dataset.theme=theme},theme)
  await openNavigation(page)
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  await page.screenshot({path:path.join(artifacts,`node-sidebar-${theme}-${viewport}.png`),fullPage:true})
  await selectNodeSection(page,'Overview');await page.waitForFunction(()=>document.querySelector('.node-detail-navigation button[aria-current=page]')?.textContent==='Overview')
  if(viewport===390){
   assert.ok(await sidebar.evaluate(el=>el.inert),'Selecting a section closes the mobile drawer')
   await openNavigation(page);await page.keyboard.press('Escape');assert.ok(await sidebar.evaluate(el=>el.inert));assert.ok(await toggle.evaluate(el=>el===document.activeElement))
  }
  await selectNodeSection(page,'Node settings')
 }
 await page.emulateMedia({reducedMotion:'reduce'})
 assert.equal(await page.locator('.node-detail-page').evaluate(el=>getComputedStyle(el).animationName),'none')
 await openNavigation(page);await detail.getByRole('button',{name:'Back to home',exact:true}).click()
 await page.locator('.nodes-dashboard').waitFor();assert.deepEqual(errors,[])
 console.log('Node sidebar passed: card entry, context replacement, top return, width/collapse reuse, refresh/history, mobile dismissal/Escape focus, reduced motion; 4 layouts.')
}
