const {fillExpanded,editorFor}=require('./expanded-textarea.cjs')
const assert=require('node:assert/strict')
const http=require('node:http')
const {selectValue,readOptions}=require('./arc-controls.cjs')
module.exports=async function({page,context,base,headers,catalog}){
 const operation=name=>{const value=catalog.operations.find(o=>o.name===name);assert.ok(value);return value}
 const providers=await(await context.request.get(base+operation('channels.options').path)).json()
 const form=page.locator('.alert-channel-form')
 const options=await readOptions(form.locator('#alert-channel-provider'))
 assert.deepEqual(options.map(o=>o.value),providers.providers.map(p=>p.id))
 const compact=form.locator('#alert-channel-body');await compact.waitFor()
 const before=await compact.boundingBox(),ordinary=await form.locator('#alert-channel-url').boundingBox()
 assert.ok(before&&ordinary);assert.ok(Math.abs(before.width-ordinary.width)<1&&Math.abs(before.height-ordinary.height)<1,'Collapsed multi-line fields match ordinary control dimensions')
 await compact.focus();await page.keyboard.press('Enter');const opened=page.locator('.expanded-textarea-panel:visible textarea');await opened.waitFor();assert.ok(await opened.evaluate(el=>el===document.activeElement))
 await opened.fill('Temporary draft');await page.keyboard.press('Escape');await opened.waitFor({state:'detached'});assert.ok(await compact.evaluate(el=>el===document.activeElement))
 const restored=await editorFor(compact);assert.equal(await restored.inputValue(),'Temporary draft');await restored.fill('');await page.locator('.expanded-textarea-panel:visible .expanded-textarea-actions button').click();await restored.waitFor({state:'detached'})
 const waitSave=()=>page.waitForResponse(r=>r.request().method()==='POST'&&new URL(r.url()).pathname===operation('channels.create').path)
 await form.getByLabel('Name',{exact:true}).fill('Private Telegram fixture')
 await selectValue(form.locator('#alert-channel-provider'),'telegram')
 assert.equal(await form.locator('#alert-channel-url').count(),0)
 await form.locator('#alert-channel-chat').fill('-100123')
 await form.locator('#alert-channel-secret').fill('123:private_telegram_token')
 await form.getByRole('checkbox',{name:'Enable channel',exact:true}).uncheck()
 let response=waitSave();await form.getByRole('button',{name:'Save channel',exact:true}).click()
 let saved=await response;assert.equal(saved.status(),200,await saved.text());const telegram=(await saved.json()).channel
 assert.equal(telegram.config.provider,'telegram');assert.equal(telegram.hasSecret,true)
 assert.ok(!JSON.stringify(telegram).includes('private_telegram_token'))
 const row=page.locator('.channel-list article').filter({hasText:'Private Telegram fixture'});await row.waitFor()
 await row.getByRole('button',{name:'Edit',exact:true}).click()
 assert.equal(await form.locator('#alert-channel-secret').inputValue(),'')
 const update=operation('channels.update').path.replace('{id}',telegram.id)
 response=page.waitForResponse(r=>new URL(r.url()).pathname===update&&r.request().method()==='PUT')
 await form.getByRole('button',{name:'Save channel',exact:true}).click();assert.equal((await response).status(),200)
 const current=(await(await context.request.get(base+operation('channels.list').path)).json()).channels.find(c=>c.id===telegram.id)
 assert.equal(current.hasSecret,true)
 await context.request.delete(base+operation('channels.delete').path.replace('{id}',current.id),{headers,data:{revision:current.revision}})
 let received
 const receiver=http.createServer((req,res)=>{let body='';req.on('data',data=>body+=data);req.on('end',()=>{received={method:req.method,authorization:req.headers.authorization,body:JSON.parse(body)};res.writeHead(204);res.end()})})
 await new Promise(resolve=>receiver.listen(0,'127.0.0.1',resolve))
 let webhook
 try{
 await form.getByLabel('Name',{exact:true}).fill('Local webhook fixture')
 await form.locator('#alert-channel-url').fill('http://127.0.0.1:'+receiver.address().port)
 await form.locator('#alert-channel-secret').fill('private_bearer_token')
 await selectValue(form.locator('#alert-channel-method'),'PATCH')
 await fillExpanded(form.locator('#alert-channel-body'),'{"text":"{{message}}"}')
 await fillExpanded(form.locator('#alert-channel-headers'),'{"X-NodeDance-Fixture":"private_header"}')
 response=waitSave();await form.getByRole('button',{name:'Save channel',exact:true}).click();saved=await response;assert.equal(saved.status(),200,await saved.text());webhook=(await saved.json()).channel
 assert.equal(webhook.hasHeaders,true)
 const webhookRow=page.locator('.channel-list article').filter({hasText:'Local webhook fixture'});await webhookRow.waitFor()
 await webhookRow.getByRole('button',{name:'Send test',exact:true}).click()
 await page.locator('.alert-deliveries').waitFor()
 for(let attempt=0;attempt<100&&!received;attempt++)await page.waitForTimeout(100)
 assert.ok(received,'Isolated receiver must receive the actual queued notification')
 assert.equal(received.method,'PATCH');assert.equal(received.authorization,'Bearer private_bearer_token');assert.match(received.body.text,/notification channel test/)
 assert.ok(!(await page.evaluate(()=>JSON.stringify({...localStorage,...sessionStorage}))).includes('private_bearer_token'))
 }finally{
 if(webhook)await context.request.delete(base+operation('channels.delete').path.replace('{id}',webhook.id),{headers,data:{revision:webhook.revision}})
 receiver.close();receiver.closeAllConnections()
 }
 await page.getByRole('tab',{name:'Notification channels',exact:true}).click();await form.waitFor()
 console.log('Notification channels: discovered providers, redacted edit and queued local Webhook passed.')
}
