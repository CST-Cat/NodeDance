const assert=require('node:assert/strict'),path=require('node:path')
const {setBrowserLanguage}=require('./browser-language.cjs')
module.exports=async function({page,base,artifacts}){
 await setBrowserLanguage(page,'en-US')
 await page.goto(base+'/#/settings')
 const row=page.locator('.profile-preferences-row'),select=page.getByTestId('profile-language'),button=row.getByRole('combobox')
 await select.waitFor({state:'attached'})
 assert.equal(await select.inputValue(),'system')
 const writes=[],capture=request=>{if(!['GET','HEAD'].includes(request.method())&&new URL(request.url()).pathname.startsWith('/api/'))writes.push(request.method()+' '+new URL(request.url()).pathname)}
 page.on('request',capture)
 await button.click();await page.getByRole('option',{name:'Simplified Chinese',exact:true}).click()
 await page.waitForFunction(()=>document.documentElement.lang==='zh-CN')
 assert.equal(await page.evaluate(()=>localStorage.getItem('nodedance.locale')),'zh-CN')
 await page.reload();await select.waitFor({state:'attached'})
 assert.equal(await select.inputValue(),'zh-CN')
 assert.equal(await page.locator('html').getAttribute('lang'),'zh-CN')
 await setBrowserLanguage(page,'en-US','zh-CN')
 assert.equal(await page.locator('html').getAttribute('lang'),'zh-CN')
 for(const language of ['zh-CN','en','system'])for(const theme of ['light','dark'])for(const width of [320,390,1440]){
  await select.selectOption(language)
  await page.setViewportSize({width,height:900})
  await page.locator('.app-shell').evaluate((el,theme)=>{el.dataset.theme=theme;document.documentElement.dataset.theme=theme},theme)
  await page.evaluate(()=>document.fonts.ready)
  await button.evaluate(el=>Promise.all(el.getAnimations().map(animation=>animation.finished.catch(()=>{}))))
  const geometry=await row.evaluate(el=>{
   const color=el.querySelector('.color-field'),language=el.querySelector('.profile-language-field')
   const c=color.querySelector('.color-control').getBoundingClientRect(),l=language.querySelector('.u031-btn').getBoundingClientRect(),card=el.closest('.settings-card').getBoundingClientRect()
   const caption=language.querySelector('.u031-v')
   return {color:c.toJSON(),language:l.toJSON(),card:card.toJSON(),labels:[color.querySelector('span').getBoundingClientRect().top,language.querySelector('span').getBoundingClientRect().top],captionFits:caption.scrollWidth<=caption.clientWidth+1&&caption.getBoundingClientRect().height<=l.height-10}
  })
  assert.ok(geometry.language.left>geometry.color.right,'Language control is to the right of background color')
  assert.ok(Math.abs(geometry.labels[0]-geometry.labels[1])<1,'Labels align horizontally')
  assert.ok(Math.abs(geometry.color.top-geometry.language.top)<1&&Math.abs(geometry.color.bottom-geometry.language.bottom)<1,'Controls share top/bottom edges: '+JSON.stringify(geometry))
  assert.ok(geometry.color.left>=geometry.card.left&&geometry.language.right<=geometry.card.right,'Both controls stay inside the card')
  assert.ok(geometry.captionFits,'Language caption fits without truncation: '+JSON.stringify(geometry))
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Settings do not overflow the viewport')
  await row.screenshot({path:path.join(artifacts,`profile-language-${language}-${theme}-${width}.png`)})
  await button.click()
  const popup=page.locator('body > .u031-list');await popup.waitFor()
  const bounds=await popup.boundingBox();assert.ok(bounds.x>=0&&bounds.x+bounds.width<=width+1,'Language menu fits the viewport')
  await page.keyboard.press('Escape')
 }
 await select.selectOption('system')
 assert.equal(await page.locator('html').getAttribute('lang'),'en')
 await setBrowserLanguage(page,'zh-CN')
 assert.equal(await page.locator('html').getAttribute('lang'),'zh-CN')
 await setBrowserLanguage(page,'en-US')
 assert.deepEqual(writes,[],'Language selection remains browser-local')
 page.off('request',capture)
 console.log('Profile language passed: beside background color, aligned labels/controls, no overflow or clipped captions at 320/390/1440, light/dark, actual dropdown, immediate preference, refresh persistence and browser-default recovery.')
}
