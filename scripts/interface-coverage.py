#!/usr/bin/env python3
"""Generate/check interface coverage from the shared Core and terminal catalogues."""
import argparse
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
catalog = json.loads(subprocess.check_output(
    ['go', 'run', './cmd/nodedance', 'operations', '--lang', 'en'], cwd=ROOT, text=True))
remote = [operation for operation in catalog['operations'] if operation['transport'] != 'local']
local = [operation for operation in catalog['operations'] if operation['transport'] == 'local']
lines = [
    '# Interface coverage / 接口能力对照', '',
    'Generated by `python3 scripts/interface-coverage.py` from the shared catalogue. '
    'Use `--check` to detect drift. The running Core remains authoritative; clients discover '
    'its actual contract. Rows describe entry/executor coverage, not a claim that every '
    'root/Docker side effect has been integration-tested.', '',
    'CLI and TUI share `terminalOperations`, `executeFinite`, the Core client, JSONL streams, '
    'interactive terminal, and update workflow. Web graphical interactions may differ; '
    'shared management changes use the same Core contract.', '',
    f'## Remote operations ({len(remote)})', '',
    '| Operation | Transport | Path / query inputs | Extra headers | Observe until completion | CLI / TUI / Web |',
    '| --- | --- | --- | --- | --- | --- |',
]
supported = {'json', 'upload', 'download', 'multipart', 'terminal', 'websocket'}
for operation in sorted(remote, key=lambda operation: operation['name']):
    if operation['transport'] not in supported:
        raise SystemExit('Unhandled transport: ' + operation['transport'])
    inputs = ', '.join(operation['parameters'] + operation['query']) or '—'
    headers = ', '.join(operation.get('headers', {})) or '—'
    completion = operation.get('completion', {}).get('operation', '—')
    lines.append(f"| `{operation['name']}` | {operation['transport']} | {inputs} | {headers} | {completion} | discovered / shared execution / discovered |")
lines += ['', f'## Local maintenance and terminal workflows ({len(local)})', '',
          '| Operation | CLI and TUI | Web |', '| --- | --- | --- |']
for operation in sorted(local, key=lambda operation: operation['name']):
    lines.append(f"| `{operation['name']}` | shared local dispatch | local host operation; no remote Web privilege |")
lines += ['', '## Behavioral verification / 行为验证', '',
          '- `go test ./...`: catalogue isolation, real Core auth/schema/PNG upload/empty preference/script bounds, '
          'terminal client, shared file cleanup and completion observation, CLI and PTY TUI.',
          '- `pnpm --dir web typecheck`: schema-driven input, upload contract, completion references and stable request intents.',
          '- `pnpm --dir web audit:interfaces`: isolated real Core and browser regression checks; no Agent/root execution.',
          '- Rootful Docker/Agent/update side effects use the existing opt-in integration environments.', '']
path = ROOT / 'docs/interface-coverage.md'
text = '\n'.join(lines)
if args.check:
    if not path.exists() or path.read_text() != text:
        sys.exit('Interface coverage changed; run python3 scripts/interface-coverage.py')
    print(f'Interface coverage verified: {len(remote)} remote + {len(local)} local/workflow operations')
else:
    path.write_text(text)
    print(path)
