func TestTarRejectsUnsafeManifests(t *testing.T) {
	for _, compressed := range []bool{false, true} {
		for _, kind := range []string{"traversal", "symlink", "hardlink", "special", "duplicate", "oversize", "file-parent", "checksum"} {
			t.Run(kind+map[bool]string{true: "-gz", false: "-tar"}[compressed], func(t *testing.T) {
				if kind == "checksum" && !compressed {
					t.Skip("gzip-specific integrity")
				}
				var raw bytes.Buffer
				var gz *gzip.Writer
				writer := tar.NewWriter(&raw)
				if compressed {
					gz = gzip.NewWriter(&raw)
					writer = tar.NewWriter(gz)
				}
				header := &tar.Header{Name: "safe", Mode: 0600, Size: 4, Typeflag: tar.TypeReg}
				content := []byte("data")
				switch kind {
				case "traversal":
					header.Name = "../escape"
				case "symlink":
					header.Typeflag = tar.TypeSymlink
					header.Linkname = "/etc/passwd"
					header.Size = 0
					content = nil
				case "hardlink":
					header.Typeflag = tar.TypeLink
					header.Linkname = "/etc/passwd"
					header.Size = 0
					content = nil
				case "special":
					header.Typeflag = tar.TypeChar
					header.Size = 0
					content = nil
				case "oversize":
					header.Size = (1 << 20) + 1
					content = make([]byte, header.Size)
				case "file-parent":
					header.Name = "parent"
				}
				if err := writer.WriteHeader(header); err != nil {
					t.Fatal(err)
				}
				writer.Write(content)
				if kind == "duplicate" || kind == "file-parent" {
					next := *header
					if kind == "file-parent" {
						next.Name = "parent/child"
					}
					if err := writer.WriteHeader(&next); err != nil {
						t.Fatal(err)
					}
					writer.Write(content)
				}
				if err := writer.Close(); err != nil {
					t.Fatal(err)
				}
				if gz != nil {
					if err := gz.Close(); err != nil {
						t.Fatal(err)
					}
				}
				payload := raw.Bytes()
				if kind == "checksum" {
					payload[len(payload)-8] ^= 0xff
				}
				s, root := extendedService(t)
				os.WriteFile(filepath.Join(root, "bad"), payload, 0600)
				os.Mkdir(filepath.Join(root, "out"), 0700)
				if err := s.ExecuteExtended(context.Background(), protocol.TaskFileExtract, protocol.FileTaskSpec{Path: "/bad", NewPath: "/out"}, "bad"); err == nil {
					t.Fatal("unsafe archive accepted")
				}
				entries, err := os.ReadDir(filepath.Join(root, "out"))
				if err != nil || len(entries) != 0 {
					t.Fatal("published unsafe archive", entries, err)
				}
			})
		}
	}
}
func TestEightMiBTextEditBoundary(t *testing.T) {
	root := t.TempDir()
	s, err := New(root, protocol.DefaultFileLimit)
	if err != nil {
		t.Fatal(err)
	}
	defer s.Close()
	text := strings.Repeat("<", protocol.MaxTextFileBytes)
	os.WriteFile(filepath.Join(root, "large.txt"), []byte(text), 0600)
	content, version, err := s.ReadText("/large.txt")
	if err != nil || content != text || version == "" {
		t.Fatal("boundary read", len(content), err)
	}
	if _, err := s.SaveText("/large.txt", version, strings.Repeat(">", protocol.MaxTextFileBytes)); err != nil {
		t.Fatal("boundary write", err)
	}
	if _, err := s.SaveText("/large.txt", version, "stale"); !errors.Is(err, ErrConflict) {
		t.Fatal("conflict missing", err)
	}
	if _, err := s.SaveText("/large.txt", "", text+"!"); !errors.Is(err, ErrTextTooLarge) {
		t.Fatal("oversize text accepted", err)
	}
}
