func TestArchiveFormatsAndRestrictivePermissions(t *testing.T) {
	for _, format := range []string{"zip", "tar", "tar.gz"} {
		t.Run(format, func(t *testing.T) {
			s, root := extendedService(t)
			os.Mkdir(filepath.Join(root, "private"), 0700)
			os.WriteFile(filepath.Join(root, "private", "data"), []byte("format fixture"), 0640)
			os.Mkdir(filepath.Join(root, "out"), 0700)
			spec := protocol.FileTaskSpec{Path: "/bundle." + format, Format: format, Paths: []string{"/private"}}
			if err := s.ExecuteExtended(context.Background(), protocol.TaskFileArchive, spec, "archive"); err != nil {
				t.Fatal(err)
			}
			if err := s.ExecuteExtended(context.Background(), protocol.TaskFileExtract, protocol.FileTaskSpec{Path: spec.Path, NewPath: "/out"}, "extract"); err != nil {
				t.Fatal(err)
			}
			data, err := os.ReadFile(filepath.Join(root, "out", "private", "data"))
			if err != nil || string(data) != "format fixture" {
				t.Fatal(string(data), err)
			}
			info, err := os.Stat(filepath.Join(root, "out", "private"))
			if err != nil || info.Mode().Perm() != 0700 {
				t.Fatal("directory mode", info, err)
			}
			info, err = os.Stat(filepath.Join(root, "out", "private", "data"))
			if err != nil || info.Mode().Perm() != 0640 {
				t.Fatal("file mode", info, err)
			}
		})
	}
}
